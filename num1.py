import pandas as pd

# Создайте объект Series, значениями которого являются целые числа от 1 до 5, а индексами символы 'a', 'b', 'c', 'd', 'e'.
s = pd.Series([1, 2, 3, 4, 5], index=['a', 'b', 'c', 'd', 'e'])
print("1. s:\n", s)

# 1. С помощью обращения по явному индексу получите значение 4.
value_by_label = s['d']
print("\n1. Значение по явному индексу 'd':", value_by_label)

# 2. С помощью обращения по неявному индексу получите значение 2.
value_by_position = s.iloc[1]
print("\n2. Значение по неявному индексу 1:", value_by_position)

# 3. Добавьте в серию новый элемент.
s['f'] = 6
print("\n3. s:\n", s)

# 4. Используя операцию среза, получите значения 3, 4, 5.
slice_values = s[['c', 'd', 'e']]
print("\n4. Срез (значения 3, 4, 5):\n", slice_values)

# 5. Создайте объект DataFrame из списка [[1, 2], [5, 3], [3.7, 4.8]] с именами столбцов col1 и col2.
df = pd.DataFrame([[1, 2], [5, 3], [3.7, 4.8]], columns=['col1', 'col2'])
print("\n5. DataFrame df:\n", df)

# 6. Используя операцию индексации, получите элемент 3.7.
element_3_7 = df.loc[2, 'col1']
print("\n6. Элемент 3.7:", element_3_7)

# 7. Измените элемент 3 на 9.
df.loc[1, 'col2'] = 9
print("\n7. DataFrame df:\n", df)

# 8. Используя операцию среза, получите строки с индексами 1 и 2.
slice_rows = df.iloc[1:3]
print("\n8. Срез строк 1 и 2:\n", slice_rows)

# 9. Добавьте столбец col3, значения которого – результат поэлементного перемножения col1 и col2.
df['col3'] = df['col1'] * df['col2']
print("\n9. DataFrame df:\n", df)


